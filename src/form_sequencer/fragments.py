MANIFEST_HEADER = """\
# Fragment manifest, generated by `form-seq analyze` and safe to edit.
#   bbox: [x, y, width, height] in pixels of the cached page image (build/pages/<page>.png)
#   kind: header | table | fields | checkboxes | stamp | signature | text
#   enabled: false        -> never used (remembered when analysis is re-run)
#   locked: true          -> kept exactly as written when analysis is re-run
#   origin: manual        -> an entry you added by hand (always kept); give it a unique id
# Overlays showing every box are in build/fragments/overlay_<page>.jpg.
"""


def _masks(rgb: np.ndarray, dpi: int) -> dict[str, np.ndarray]:
    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
    block = int(dpi / 5) | 1
    ink = cv2.adaptiveThreshold(gray, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C, cv2.THRESH_BINARY_INV, block, 18)
    ink = cv2.bitwise_and(ink, (gray < 200).astype(np.uint8) * 255)  # ignore faint paper texture
    n, lab, stats, _ = cv2.connectedComponentsWithStats(ink, 8)
    small = np.where(stats[:, cv2.CC_STAT_AREA] < 4)[0]
    ink[np.isin(lab, small)] = 0

    hl, vl = max(8, int(dpi * 0.45)), max(8, int(dpi * 0.3))
    horiz = cv2.morphologyEx(ink, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_RECT, (hl, 1)))
    vert = cv2.morphologyEx(ink, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_RECT, (1, vl)))
    lines = cv2.bitwise_or(horiz, vert)
    text = cv2.bitwise_and(ink, cv2.bitwise_not(cv2.dilate(lines, np.ones((3, 3), np.uint8))))

    hsv = cv2.cvtColor(rgb, cv2.COLOR_RGB2HSV)
    color = ((hsv[..., 1] > 60) & (hsv[..., 2] < 245) & (hsv[..., 2] > 60)).astype(np.uint8) * 255
    color = cv2.morphologyEx(color, cv2.MORPH_OPEN, np.ones((2, 2), np.uint8))
    return {"gray": gray, "ink": ink, "horiz": horiz, "vert": vert, "lines": lines, "text": text, "color": color}


def _line_segments(mask: np.ndarray, axis: int, min_frac: float) -> int:
    """Count distinct ruling lines spanning at least ``min_frac`` of the region (axis 1 = horizontal)."""
    if mask.size == 0:
        return 0
    n, _, stats, _ = cv2.connectedComponentsWithStats(mask, 8)
    extent = stats[1:, cv2.CC_STAT_WIDTH if axis == 1 else cv2.CC_STAT_HEIGHT]
    return int((extent >= min_frac * mask.shape[1 if axis == 1 else 0]).sum())


def _checkbox_count(ink: np.ndarray, dpi: int) -> int:
    """Count small hollow squares: all four sides inked (letters like O or D fail this)."""
    lo, hi = dpi * 0.08, dpi * 0.26
    n, _, stats, _ = cv2.connectedComponentsWithStats(ink, 8)
    count = 0
    for x, y, w, h, area in stats[1:]:
        if not (lo <= w <= hi and lo <= h <= hi and 0.75 <= w / h <= 1.33):
            continue
        box = ink[y:y + h, x:x + w] > 0
        b = max(2, int(min(w, h) * 0.15))
        sides = [box[:b].any(0).mean(), box[-b:].any(0).mean(), box[:, :b].any(1).mean(), box[:, -b:].any(1).mean()]
        if min(sides) > 0.85 and area < 0.6 * w * h:
            count += 1
    return count


def _text_height(text: np.ndarray, dpi: int) -> float:
    n, _, stats, _ = cv2.connectedComponentsWithStats(text, 8)
    h = stats[1:, cv2.CC_STAT_HEIGHT]
    h = h[(h > dpi * 0.04) & (h < dpi * 0.6)]
    return float(np.median(h)) if h.size else 0.0


def _largest_color_blob(color: np.ndarray, dpi: int) -> tuple[int, int]:
    """Width and height of the biggest connected coloured-ink shape (stamps, cursive signatures)."""
    if not color.any():
        return 0, 0
    joined = cv2.dilate(color, np.ones((max(3, dpi // 30),) * 2, np.uint8))
    n, _, stats, _ = cv2.connectedComponentsWithStats(joined, 8)
    if n < 2:
        return 0, 0
    i = 1 + int(np.argmax(stats[1:, cv2.CC_STAT_AREA]))
    return int(stats[i, cv2.CC_STAT_WIDTH]), int(stats[i, cv2.CC_STAT_HEIGHT])


def _text_share(text: np.ndarray, ink: np.ndarray, dpi: int) -> float:
    """Share of the ink that belongs to character-sized shapes."""
    total = np.count_nonzero(ink)
    if total == 0:
        return 1.0
    n, _, stats, _ = cv2.connectedComponentsWithStats(text, 8)
    hh, ww, area = stats[1:, cv2.CC_STAT_HEIGHT], stats[1:, cv2.CC_STAT_WIDTH], stats[1:, cv2.CC_STAT_AREA]
    glyph = (hh >= dpi * 0.04) & (hh <= dpi * 0.3) & (ww <= dpi * 0.5)
    return float(area[glyph].sum()) / total


def classify(m: dict, box: tuple[int, int, int, int], page_shape, dpi: int, page_text_h: float) -> tuple[str, float]:
    x, y, w, h = box
    sl = (slice(y, y + h), slice(x, x + w))
    ink = m["ink"][sl]
    ink_px = max(1, int(np.count_nonzero(ink)))
    color_frac = np.count_nonzero(m["color"][sl]) / ink_px
    bw, bh = _largest_color_blob(m["color"][sl], dpi)
    h_full = _line_segments(m["horiz"][sl], 1, 0.6)
    h_any = _line_segments(m["horiz"][sl], 1, 0.12)
    v_full = _line_segments(m["vert"][sl], 0, 0.5)
    boxes = _checkbox_count(ink, dpi)
    th = _text_height(m["text"][sl], dpi)

    if color_frac > 0.3 and min(bw, bh) > dpi * 0.8 and 0.6 <= bw / bh <= 1.7 and bw * bh > 0.5 * w * h:
        return "stamp", 0.9
    if color_frac > 0.15 and bw > dpi * 1.0 and bh < dpi * 0.8 and h < dpi * 1.6:
        return "signature", 0.8
    if h_full >= 3 and v_full >= 2:
        return "table", 0.9
    if min(w, h) >= 0.9 * dpi and _text_share(m["text"][sl], ink, dpi) < 0.35:
        return "diagram", 0.85  # line drawing, chart, figure: mostly non-text ink
    if y < page_shape[0] * 0.15 and th > page_text_h * 1.3 and w > page_shape[1] * 0.3:
        return "header", 0.85
    if boxes >= 2 and boxes >= h_any:
        return "checkboxes", 0.75
    if h_any >= 1:
        return "fields", 0.7
    return "text", 0.5


def _gaps(profile: np.ndarray, min_gap: int) -> list[tuple[int, int]]:
    """Runs of empty positions (start, end) at least ``min_gap`` long, excluding the ends."""
    empty = profile == 0
    runs, start = [], None
    for i, e in enumerate(empty):
        if e and start is None:
            start = i
        elif not e and start is not None:
            if i - start >= min_gap and start > 0:
                runs.append((start, i))
            start = None
    return runs


def _rules(line_mask: np.ndarray, axis: int, frac: float = 0.75) -> list[tuple[int, int]]:
    """Runs of rows (axis=1) or columns (axis=0) crossed by a ruling line spanning most of the region."""
    span = line_mask.shape[axis]
    hit = np.count_nonzero(line_mask, axis=axis) >= frac * span
    runs, start = [], None
    for i, h in enumerate(np.append(hit, False)):
        if h and start is None:
            start = i
        elif not h and start is not None:
            runs.append((start, i))
            start = None
    return runs


def _xy_cut(layers: tuple[np.ndarray, np.ndarray, np.ndarray], x: int, y: int, gy: int, gx: int,
            depth: int, out: list) -> None:
    """Recursive XY-cut: split at the widest whitespace first, else along ruling lines.

    ``layers`` = (ink without colour, horizontal rules, vertical rules), all cropped to
    the current region. Whitespace separates blocks on open layouts; on dense ruled
    forms (tax returns, personnel forms) there is no whitespace, so full-width rules
    and then full-height rules become the cut lines. Every node is a candidate, and so
    is every run of 2-4 adjacent siblings, which recovers groups such as "section band
    + its fields" or "question + checkboxes".
    """
    ink, hl, vl = layers
    rows = np.count_nonzero(ink, axis=1) > 1 + ink.shape[1] // 400  # a stray speck does not fill a gap
    cols = np.count_nonzero(ink, axis=0) > 1 + ink.shape[0] // 400
    ys, xs = np.nonzero(rows)[0], np.nonzero(cols)[0]
    if ys.size == 0 or xs.size == 0:
        return
    sl = (slice(ys[0], ys[-1] + 1), slice(xs[0], xs[-1] + 1))
    ink, hl, vl = ink[sl], hl[sl], vl[sl]
    x, y = x + int(xs[0]), y + int(ys[0])
    out.append((x, y, ink.shape[1], ink.shape[0]))
    if depth <= 0:
        return

    hgaps = _gaps(np.count_nonzero(ink, axis=1) > 1 + ink.shape[1] // 400, gy)
    vgaps = _gaps(np.count_nonzero(ink, axis=0) > 1 + ink.shape[0] // 400, gx)
    ruled = False
    if hgaps or vgaps:
        # split along the axis offering the widest (relative) gap, only at gaps close to it
        hbest = max((e - s) / gy for s, e in hgaps) if hgaps else 0
        vbest = max((e - s) / gx for s, e in vgaps) if vgaps else 0
        horizontal = hbest >= vbest
        gaps, unit = (hgaps, gy) if horizontal else (vgaps, gx)
        widest = max(e - s for s, e in gaps)
        cuts = [(s, e) for s, e in gaps if e - s >= max(unit, 0.6 * widest)]
    else:
        length_h, length_w = ink.shape
        inner = lambda runs, n: [(s, e) for s, e in runs if s > 2 and e < n - 2]  # noqa: E731
        cuts = inner(_rules(hl, 1), length_h)
        horizontal = True
        if not cuts:
            cuts = inner(_rules(vl, 0), length_w)
            horizontal = False
        if not cuts:
            return
        ruled = True
    length = ink.shape[0] if horizontal else ink.shape[1]
    bounds, prev = [], 0
    for s, e in cuts:
        bounds.append((prev, s))
        prev = e
    bounds.append((prev, length))
    children: list[tuple[int, int, int, int]] = []
    for a, b in bounds:
        if b - a < 3:
            continue
        part = tuple(m[a:b] if horizontal else m[:, a:b] for m in (ink, hl, vl))
        cx, cy = (x, y + a) if horizontal else (x + a, y)
        before = len(out)
        _xy_cut(part, cx, cy, gy, gx, depth - 1, out)
        if len(out) > before:
            children.append(out[before])
    for n in (2, 3, 4) if ruled or len(children) <= 8 else ():
        for i in range(len(children) - n + 1):
            grp = children[i:i + n]
            x0 = min(c[0] for c in grp)
            y0 = min(c[1] for c in grp)
            x1 = max(c[0] + c[2] for c in grp)
            y1 = max(c[1] + c[3] for c in grp)
            out.append((x0, y0, x1 - x0, y1 - y0))


def _candidates(m: dict, dpi: int) -> list[tuple[int, int, int, int]]:
    # Coloured ink (stamps, signatures) often overlaps printed structure, which would
    # glue unrelated blocks together, so it is segmented separately.
    halo = cv2.dilate(m["color"], np.ones((max(3, dpi // 20),) * 2, np.uint8))  # faint stamp edges too
    mono = cv2.bitwise_and(m["ink"], cv2.bitwise_not(halo))
    # drop specks (JPEG/scan noise) so whitespace gaps stay empty for the XY-cut
    n, lab, stats, _ = cv2.connectedComponentsWithStats(mono, 8)
    specks = np.nonzero(stats[:, cv2.CC_STAT_AREA] < max(6, int((dpi / 60) ** 2)))[0]
    mono[np.isin(lab, specks)] = 0
    hl = cv2.bitwise_and(m["horiz"], mono)
    vl = cv2.bitwise_and(m["vert"], mono)
    boxes: list[tuple[int, int, int, int]] = []
    _xy_cut((mono, hl, vl), 0, 0, max(4, int(0.075 * dpi)), max(8, int(0.22 * dpi)), 8, boxes)
    joined = cv2.dilate(m["color"], cv2.getStructuringElement(cv2.MORPH_RECT, (int(0.22 * dpi), int(0.2 * dpi))))
    n, _, stats, _ = cv2.connectedComponentsWithStats(joined, 8)
    for s in stats[1:]:
        boxes.append(tuple(int(v) for v in s[:4]))
    return boxes


def _iou(a, b) -> float:
    ax, ay, aw, ah = a
    bx, by, bw, bh = b
    ix = max(0, min(ax + aw, bx + bw) - max(ax, bx))
    iy = max(0, min(ay + ah, by + bh) - max(ay, by))
    inter = ix * iy
    return inter / float(aw * ah + bw * bh - inter)


def _clean_edges(ink: np.ndarray, x: int, y: int, w: int, h: int, pad: int) -> tuple[int, int, int, int]:
    """Pad a box, but never let an edge slice through neighbouring ink.

    Each side grows by up to ``pad``; if that margin contains foreign ink the edge
    stops just before it, so crops show whole characters/lines or nothing.
    """
    H, W = ink.shape
    rows = lambda a, b: ink[max(0, a):b, x:x + w].any(axis=1)  # noqa: E731
    cols = lambda a, b: ink[y:y + h, max(0, a):b].any(axis=0)  # noqa: E731
    top = rows(y - pad, y)[::-1]
    y0 = y - (int(np.argmax(top)) if top.any() else top.size)
    bot = rows(y + h, y + h + pad)
    y1 = y + h + (int(np.argmax(bot)) if bot.any() else bot.size)
    left = cols(x - pad, x)[::-1]
    x0 = x - (int(np.argmax(left)) if left.any() else left.size)
    right = cols(x + w, x + w + pad)
    x1 = x + w + (int(np.argmax(right)) if right.any() else right.size)
    return max(0, x0), max(0, y0), min(W, x1), min(H, y1)


def detect_page(rgb: np.ndarray, dpi: int, cfg: dict) -> list[dict]:
    H, W = rgb.shape[:2]
    m = _masks(rgb, dpi)
    page_text_h = _text_height(m["text"], dpi) or dpi * 0.12
    min_side = cfg["min_region_inches"] * dpi
    max_area = cfg["max_region_fraction"] * W * H
    pad = int(0.06 * dpi)

    found = []
    for box in _candidates(m, dpi):
        x, y, w, h = box
        if w < min_side or h < min_side or w * h > max_area:
            continue
        if (x <= 2) + (y <= 2) + (x + w >= W - 2) + (y + h >= H - 2) >= 2:
            continue  # scan border / edge shadow
        density = np.count_nonzero(m["ink"][y:y + h, x:x + w]) / float(w * h)
        if not 0.006 <= density <= 0.55:
            continue
        x0, y0, x1, y1 = _clean_edges(m["ink"], x, y, w, h, pad)
        kind, conf = classify(m, (x, y, w, h), (H, W), dpi, page_text_h)
        size = min(1.0, (w * h) / (dpi * dpi * 5.0))
        found.append({"bbox": [x0, y0, x1 - x0, y1 - y0], "kind": kind, "ink": round(float(density), 3),
                      "score": round(float(conf * (0.4 + 0.6 * size)), 3)})

    found.sort(key=lambda f: -f["score"])
    kept: list[dict] = []
    for f in found:
        if all(_iou(f["bbox"], k["bbox"]) < 0.5 for k in kept):
            kept.append(f)
    return kept[:40]


def _frag_id(source: str, page: int, bbox) -> str:
    h = hashlib.sha1(f"{source}|{page}|{list(bbox)}".encode()).hexdigest()[:8]
    return f"f{h}"


def extract(project: Project, settings: dict, pages: list[PageRef], log=lambda m: None) -> dict:
    """Detect fragments on every page, never inside forbidden areas (photos, email addresses)."""
    dpi = int(settings["documents"]["dpi"])
    old = load_manifest(project) if project.manifest_path.exists() else None
    old_frags = {f["id"]: f for f in (old or {}).get("fragments", [])}
    pcfg = settings["photos"]
    photos.ensure_overrides_file(project.exclusions_path)
    overrides = photos.load_overrides(project.exclusions_path)

    frags = [f for f in old_frags.values() if f.get("origin") == "manual" or f.get("locked")]
    kept_ids = {f["id"] for f in frags}
    page_dicts, review = [], {}
    lines = textscan.page_lines(project, [p.asdict() for p in pages], settings["emails"], log)
    for ref in pages:
        rgb = load_page(project, ref.asdict())
        found = photos.detect(rgb, dpi, pcfg) if pcfg["enabled"] else {"regions": [], "page": "ok", "reason": ""}
        found["regions"] = found["regions"] + emails.find(lines[ref.key], ref.width, ref.height, settings["emails"], dpi) \
            + qr.detect(rgb, dpi, settings["qr"])
        scr = scramble.detect(rgb, lines[ref.key], dpi, settings["scramble"], [r["bbox"] for r in found["regions"]])
        scr_final = scramble.apply_overrides(ref.key, scr, overrides)
        final = photos.apply_overrides(ref.key, ref.width, ref.height, found, overrides)
        allowed = list((overrides.get(ref.key, {}) or {}).get("allow", []) or [])
        review[ref.key] = {"detected": found, "final": final, "allowed": allowed, "scramble": scr,
                           "scramble_final": scr_final}
        pd = ref.asdict()
        pd["forbidden"] = final["forbidden"]
        pd["rejected"] = final["rejected"]
        pd["scramble"] = scr_final
        page_dicts.append(pd)
        if final["rejected"]:
            continue
        for det in detect_page(rgb, dpi, settings["documents"]):
            if photos.intersects(det["bbox"], final["forbidden"]):
                continue  # never extract across a photo
            fid = _frag_id(ref.source, ref.page, det["bbox"])
            if fid in kept_ids:
                continue
            prev = old_frags.get(fid)
            frags.append({
                "id": fid, "page": ref.key, "source": ref.source, "source_page": ref.page,
                "bbox": [int(v) for v in det["bbox"]], "kind": det["kind"], "ink": det["ink"], "score": det["score"],
                "enabled": prev.get("enabled", True) if prev else True,
                "locked": False, "origin": "auto",
            })
    # manual and locked entries are kept, but never used if they touch a forbidden area
    forbidden = {pd["key"]: pd["forbidden"] for pd in page_dicts}
    for f in frags:
        if f.get("origin") == "manual" or f.get("locked"):
            if photos.intersects(f["bbox"], forbidden.get(f["page"], [])):
                f["excluded"] = "intersects a forbidden (photo) area"
            else:
                f.pop("excluded", None)
    frags.sort(key=lambda f: (f["page"], f["bbox"][1], f["bbox"][0]))
    manifest = {"dpi": dpi, "pages": page_dicts, "fragments": frags}
    save_manifest(project, manifest)
    _save_exclusions(project, review)
    return manifest


def usable(f: dict) -> bool:
    return f.get("enabled", True) and not f.get("excluded")


def _save_exclusions(project: Project, review: dict) -> None:
    """build/exclusions.yaml: what detection found (a record; edit <project>/exclusions.yaml to correct)."""
    data = {k: {"page": v["detected"]["page"], "reason": v["detected"]["reason"],
                "regions": v["detected"]["regions"], "forbidden": v["final"]["forbidden"],
                "rejected": v["final"]["rejected"]}
            for k, v in review.items() if v["detected"]["regions"] or v["final"]["rejected"] or v["final"]["forbidden"]}
    head = "# Photo detection results (generated). To correct them, edit exclusions.yaml in the project folder.\n"
    body = yaml.safe_dump(data, sort_keys=False, default_flow_style=None, width=110)
    (project.build / "exclusions.yaml").write_text(head + body, encoding="utf-8")
    (project.build / "exclusions_review.json").write_text(json.dumps(review), encoding="utf-8")


def save_manifest(project: Project, manifest: dict) -> None:
    project.manifest_path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(manifest, sort_keys=False, default_flow_style=None, width=110)
    project.manifest_path.write_text(MANIFEST_HEADER + body, encoding="utf-8")


def load_manifest(project: Project) -> dict:
    with open(project.manifest_path, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def crop(project: Project, manifest: dict, frag: dict, _cache: dict = {}) -> np.ndarray:
    """Cut a fragment from its cached page image (RGB uint8)."""
    pages = {p["key"]: p for p in manifest["pages"]}
    key = frag["page"]
    if key not in _cache:
        _cache.clear() if len(_cache) > 8 else None
        # logos and institutional titles are scrambled before any crop is taken
        _cache[key] = scramble.apply(load_page(project, pages[key]), pages[key].get("scramble", []), key)
    img = _cache[key]
    x, y, w, h = frag["bbox"]
    return img[max(0, y):y + h, max(0, x):x + w].copy()


def write_inspection(project: Project, manifest: dict) -> list[Path]:
    """Per-page overlays of all boxes, a contact sheet of enabled crops, and crop PNGs."""
    out_dir = project.build / "fragments"
    crops_dir = out_dir / "crops"
    crops_dir.mkdir(parents=True, exist_ok=True)
    unreadable = []  # inspection files the disk refuses to touch (e.g. filesystem damage) are skipped
    for old in crops_dir.glob("*.png"):
        try:
            old.unlink()
        except OSError:
            unreadable.append(old.name)
    written = []
    label_font = font("sans-bold", 16)
    for page in manifest["pages"]:
        img = Image.fromarray(load_page(project, page))
        d = ImageDraw.Draw(img)
        for f in manifest["fragments"]:
            if f["page"] != page["key"]:
                continue
            x, y, w, h = f["bbox"]
            col = KIND_COLORS.get(f["kind"], (0, 0, 0)) if usable(f) else (180, 180, 180)
            d.rectangle([x, y, x + w, y + h], outline=col, width=3)
            d.text((x + 4, y + 2), f"{f['id']} {f['kind']}", font=label_font, fill=col)
        for x, y, w, h in page.get("forbidden", []):
            d.rectangle([x, y, x + w, y + h], outline=(220, 0, 0), width=6)
            d.text((x + 6, y + 6), "EXCLUDED (photo)", font=label_font, fill=(220, 0, 0))
        path = out_dir / f"overlay_{page['key']}.jpg"
        img.save(path, quality=85)
        written.append(path)

    enabled = [f for f in manifest["fragments"] if usable(f)]
    thumbs = []
    for f in enabled:
        c = crop(project, manifest, f)
        try:
            Image.fromarray(c).save(crops_dir / f"{f['id']}_{f['kind']}.png")
        except OSError:
            unreadable.append(f"{f['id']}_{f['kind']}.png")
        t = Image.fromarray(c)
        t.thumbnail((300, 220))
        thumbs.append((f, t))
    for old in out_dir.glob("contact_sheet*.jpg"):
        old.unlink()
    per_sheet, cols = 240, 6  # keeps each sheet well under JPEG's 65535 px limit
    for n, start in enumerate(range(0, len(thumbs), per_sheet), start=1):
        chunk = thumbs[start:start + per_sheet]
        rows = (len(chunk) + cols - 1) // cols
        sheet = Image.new("RGB", (cols * 320, rows * 260), (235, 235, 235))
        d = ImageDraw.Draw(sheet)
        for i, (f, t) in enumerate(chunk):
            cx, cy = (i % cols) * 320 + 10, (i // cols) * 260 + 10
            sheet.paste(t, (cx, cy))
            d.text((cx, cy + 226), f"{f['id']} {f['kind']}", font=label_font, fill=KIND_COLORS.get(f["kind"], (0, 0, 0)))
        path = out_dir / ("contact_sheet.jpg" if len(thumbs) <= per_sheet else f"contact_sheet_{n:02d}.jpg")
        sheet.save(path, quality=85)
        written.append(path)
    if unreadable:
        import warnings
        warnings.warn(f"{len(unreadable)} inspection file(s) in {crops_dir} could not be replaced (disk error), "
                      f"e.g. {unreadable[0]}; check the drive (chkdsk)")
    return written
