"""Find visually distinct regions on document pages and keep them in an editable manifest.

Detection is classical computer vision (OpenCV):
  * adaptive threshold -> ink mask
  * long morphological openings -> horizontal / vertical ruling lines
  * saturation mask -> coloured ink (stamps, signatures)
  * dilation at several scales -> candidate blocks (words -> lines -> groups)
Each candidate is classified from its contents (ruling-line counts, checkbox-like squares,
colour share, text height, position on the page).

The manifest (build/manifest.yaml) is the source of truth for rendering; crops are cut
from the page cache at render time, so editing a bbox there takes effect immediately.
Entries with ``origin: manual`` or ``locked: true`` survive re-analysis unchanged, and
``enabled: false`` on an auto entry is remembered across re-analysis.
"""

